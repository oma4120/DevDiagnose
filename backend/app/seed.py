def current_bug_ref(bugs: list[dict]) -> str:
    """Return the next bug id/ref (e.g. b1043 / #1043) based on seeded or existing bugs."""
    max_num = 1042
    for b in bugs:
        ref = b.get("ref", "")
        digits = "".join(ch for ch in ref if ch.isdigit())
        if digits:
            max_num = max(max_num, int(digits))
    return f"b{max_num + 1}", f"#{max_num + 1}"
